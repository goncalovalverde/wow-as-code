import { Command } from "commander";
import { existsSync, readFileSync } from "node:fs";
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { resolveRules } from "../lib/load.js";
import { createSourceProvider } from "../lib/sources.js";
import { TARGET_IDS, type TargetId } from "../lib/sync/render.js";
import { planSync, type SyncEntry } from "../lib/sync/plan.js";
import type { OutputFormat } from "../lib/types.js";

function parseTargets(value: string | undefined): TargetId[] {
  if (!value) return TARGET_IDS;
  const requested = value.split(",").map((item) => item.trim());
  const unknown = requested.filter((item) => !TARGET_IDS.includes(item as TargetId));
  if (unknown.length > 0) {
    throw new Error(`Unknown target(s): ${unknown.join(", ")}. Valid: ${TARGET_IDS.join(", ")}`);
  }
  return requested as TargetId[];
}

function report(entries: SyncEntry[], format: OutputFormat): void {
  if (format === "json") {
    const summary = entries.map(({ target, path, status }) => ({ target, path, status }));
    console.log(JSON.stringify(summary, null, 2));
    return;
  }
  for (const { path, status } of entries) {
    console.log(`${status.padEnd(10)} ${path}`);
  }
}

export const syncCommand = new Command("sync")
  .description("Compile wow/ rules into agent instruction files (AGENTS.md, CLAUDE.md, ...)")
  .option("-d, --dir <path>", "wow directory path", "wow")
  .option("-r, --root <path>", "repository root where files are written", ".")
  .option("-t, --target <targets>", `comma-separated targets (${TARGET_IDS.join("|")}); default all`)
  .option("--check", "do not write; exit 1 if generated files are missing or out of date")
  .option("--strict", "fail if any inherited source cannot be loaded")
  .option("--force", "overwrite existing files that were not generated by wow sync")
  .option("-f, --format <format>", "output format (text|json)", "text")
  .action(async (options) => {
    const root = resolve(process.cwd(), options.root);
    const provider = createSourceProvider();
    const { rules, warnings } = await resolveRules(resolve(process.cwd(), options.dir), provider).finally(
      () => provider.dispose?.()
    );
    warnings.forEach((warning) => console.error(`⚠ ${warning}`));
    if (options.strict && warnings.length > 0) {
      console.error("Aborting: inherited sources could not be fully resolved (--strict).");
      process.exit(1);
    }
    const targets = parseTargets(options.target);

    const readExisting = (path: string) => {
      const absolute = join(root, path);
      return existsSync(absolute) ? readFileSync(absolute, "utf-8") : undefined;
    };
    const entries = planSync(rules, targets, readExisting, { force: options.force });
    report(entries, options.format);

    const blocked = entries.filter((entry) => entry.status === "blocked");
    const pending = entries.filter((entry) => entry.status !== "unchanged");

    if (options.check) {
      process.exit(pending.length > 0 ? 1 : 0);
    }
    if (blocked.length > 0) {
      console.error(
        `Refusing to overwrite hand-written file(s): ${blocked.map((e) => e.path).join(", ")}. Use --force to replace.`
      );
      process.exit(1);
    }
    for (const entry of pending) {
      const absolute = join(root, entry.path);
      await mkdir(dirname(absolute), { recursive: true });
      await writeFile(absolute, entry.content, "utf-8");
    }
  });
